"""Lift a whole analysed program: functions, their prototypes and the dispatch table.

The dispatch table maps each recompiled function's address to its C function;
``gba_lookup`` (prefixed in tests, so several programs can share one binary)
finds the function for an address with a binary search and hands anything
else to the runtime's ``gba_missing``.
"""

from dataclasses import dataclass

from gbaport.analysis.cfg import Program
from gbaport.analysis.discover import Exploration
from gbaport.lift.function import function_name, lift_function

HEADER = "gba_cpu.h"
CHUNK = 256  # functions per generated .c file


@dataclass(frozen=True)
class LiftedProgram:
    prefix: str
    prototypes: str  # a declaration for every function
    functions: dict[int, str]  # entry address -> C definition
    dispatch: str  # the sorted table and the lookup function
    problems: tuple[str, ...] = ()  # instructions lifted as undefined because C cannot express them

    @property
    def lookup_name(self) -> str:
        return f"{self.prefix}gba_lookup"


def lift_program(program: Program, ex: Exploration, prefix: str = "") -> LiftedProgram:
    entries = sorted(program.functions)
    prototypes = "".join(f"uint32_t {function_name(a, prefix)}(GbaCtx *ctx);\n" for a in entries)
    prototypes += f"GbaFn {prefix}gba_lookup(GbaCtx *ctx, uint32_t addr);\n"
    problems: list[str] = []
    functions = {
        a: lift_function(program.functions[a], program, ex, prefix, problems) for a in entries
    }
    unique = tuple(dict.fromkeys(problems))  # a block shared by several functions reports once
    return LiftedProgram(prefix, prototypes, functions, _dispatch(entries, prefix), unique)


def single_source(lifted: LiftedProgram) -> str:
    """One C file holding the whole program (it includes gba_cpu.h)."""
    parts = [f'#include "{HEADER}"\n', lifted.prototypes, *lifted.functions.values()]
    return "\n".join([*parts, lifted.dispatch])


def program_files(lifted: LiftedProgram, chunk: int = CHUNK) -> dict[str, str]:
    """The generated sources by file name: a header, code files and the dispatch table."""
    files = {"gba_program.h": _program_header(lifted)}
    bodies = list(lifted.functions.values())
    for n, start in enumerate(range(0, len(bodies), chunk)):
        code = '#include "gba_program.h"\n\n' + "\n".join(bodies[start : start + chunk])
        files[f"gba_code_{n:03d}.c"] = code
    files["gba_dispatch.c"] = '#include "gba_program.h"\n\n' + lifted.dispatch
    return files


def _program_header(lifted: LiftedProgram) -> str:
    return (
        "/* Generated by gbaport: declarations of every recompiled function. */\n"
        "#ifndef GBA_PROGRAM_H\n#define GBA_PROGRAM_H\n\n"
        f'#include "{HEADER}"\n\n{lifted.prototypes}\n#endif\n'
    )


def _dispatch(entries: list[int], prefix: str) -> str:
    lines = []
    if entries:
        lines.append(f"static const struct {{ uint32_t addr; GbaFn fn; }} {prefix}table[] = {{")
        lines += [f"    {{0x{a:08x}u, {function_name(a, prefix)}}}," for a in entries]
        lines.append("};")
    lines += [
        "",
        f"GbaFn {prefix}gba_lookup(GbaCtx *ctx, uint32_t addr)",
        "{",
        "    addr &= ~1u;",
    ]
    if entries:
        lines += [
            f"    uint32_t lo = 0, hi = {len(entries)};",
            "    while (lo < hi) {",
            "        uint32_t mid = (lo + hi) / 2;",
            f"        uint32_t found = {prefix}table[mid].addr;",
            "        if (found == addr)",
            f"            return {prefix}table[mid].fn;",
            "        if (found < addr)",
            "            lo = mid + 1;",
            "        else",
            "            hi = mid;",
            "    }",
        ]
    lines += ["    return gba_missing(ctx, addr);", "}"]
    return "\n".join(lines) + "\n"
